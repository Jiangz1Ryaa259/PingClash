/** Public, synthetic fixture key only. It is in androidTest assets, never the main APK. */
internal class SubscriptionFixture : Closeable {
    val requests = AtomicInteger()
    val responseGates =
        java.util.concurrent.ConcurrentHashMap<String, java.util.concurrent.CountDownLatch>()
    val responsesWritten = java.util.concurrent.CountDownLatch(1)
    val bodies = java.util.concurrent.ConcurrentHashMap<String, String>()
    val binaryBodies = java.util.concurrent.ConcurrentHashMap<String, ByteArray>()
    val statuses = java.util.concurrent.ConcurrentHashMap<String, Int>()
    val redirects = java.util.concurrent.ConcurrentHashMap<String, String>()
    val captured = java.util.concurrent.CopyOnWriteArrayList<Map<String, String>>()
    var quotaHeader: String? = null
    var profileTitleHeader: String? = null
    var dispositionHeader: String? = null

    fun address(path: String) = "https://127.0.0.1:${socket.localPort}$path"

    private val workers = Executors.newFixedThreadPool(3)
    private val previousFactory = HttpsURLConnection.getDefaultSSLSocketFactory()
    private val socket: ServerSocket
    val source: String
        get() = "https://127.0.0.1:${socket.localPort}/redirect?fixture-token=private"

    val html: String
        get() = "https://127.0.0.1:${socket.localPort}/html?fixture-token=private"

    init {
        val asset =
            InstrumentationRegistry.getInstrumentation()
                .context
                .assets
                .open("subscription-fixture.base64")
                .use { it.readBytes() }
        // Build an in-memory store from public DER fixtures. Older Android PKCS12
        // providers cannot read the modern container MAC generated by JDK 21.
        val encoded = org.json.JSONObject(asset.toString(Charsets.UTF_8))
        val key =
            java.security.KeyFactory.getInstance("RSA")
                .generatePrivate(
                    java.security.spec.PKCS8EncodedKeySpec(
                        Base64.decode(encoded.getString("fixturePrivateDer"), Base64.DEFAULT)
                    )
                )
        val certificate =
            java.security.cert.CertificateFactory.getInstance("X.509")
                .generateCertificate(
                    Base64.decode(encoded.getString("certificate"), Base64.DEFAULT).inputStream()
                )
        val store =
            KeyStore.getInstance(KeyStore.getDefaultType()).apply {
                load(null, null)
                setKeyEntry(
                    "fixture",
                    key,
                    "public-test-password".toCharArray(),
                    arrayOf(certificate),
                )
            }
        val keys =
            KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm()).apply {
                init(store, "public-test-password".toCharArray())
            }
        val roots =
            TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm()).apply {
                init(store)
            }
        val serverContext =
            SSLContext.getInstance("TLS").apply { init(keys.keyManagers, null, null) }
        val clientContext =
            SSLContext.getInstance("TLS").apply { init(null, roots.trustManagers, null) }
        // Restore in close(). Production code never changes certificate trust or hostname checks.
        HttpsURLConnection.setDefaultSSLSocketFactory(clientContext.socketFactory)
        socket =
            serverContext.serverSocketFactory.createServerSocket(
                0,
                8,
                InetAddress.getByName("127.0.0.1"),
            )
        workers.execute {
            while (!socket.isClosed) runCatching {
                val connection = socket.accept()
                workers.execute {
                    runCatching {
                        connection.use {
                            it.soTimeout = 5000
                            val reader = it.getInputStream().bufferedReader()
                            val first = reader.readLine() ?: return@use
                            var total = first.length
                            val headers = mutableMapOf<String, String>()
                            while (true) {
                                val line = reader.readLine() ?: break
                                total += line.length
                                require(total < 32768)
                                if (line.isEmpty()) break
                                val pair = line.split(':', limit = 2)
                                if (pair.size == 2) headers[pair[0].lowercase()] = pair[1].trim()
                            }
                            captured.add(headers)
                            val path = first.split(' ').getOrNull(1)?.substringBefore('?').orEmpty()
                            requests.incrementAndGet()
                            responseGates[path]?.await(10, java.util.concurrent.TimeUnit.SECONDS)
                            val redirect =
                                first.contains(" /redirect") || redirects.containsKey(path)
                            val html = first.contains(" /html")
                            val raw =
                                "anytls://fixture-password@example.invalid:443?sni=example.invalid&insecure=1#HK%20AnyTLS"
                            val body =
                                bodies[path]
                                    ?: if (html) "<!doctype html><html>login page</html>"
                                    else Base64.encodeToString(raw.toByteArray(), Base64.NO_WRAP)
                            val payload = binaryBodies[path] ?: body.toByteArray()
                            val response =
                                if (redirect)
                                    "HTTP/1.1 302 Found\r\nLocation: ${redirects[path]?:"/subscribe"}\r\nContent-Length: 0\r\nConnection: close\r\n\r\n"
                                else
                                    "HTTP/1.1 ${statuses[path]?:200} OK\r\n" +
                                        (profileTitleHeader?.let { q -> "profile-title: $q\r\n" }
                                            ?: "") +
                                        (dispositionHeader?.let { q ->
                                            "Content-Disposition: $q\r\n"
                                        } ?: "") +
                                        (quotaHeader?.let { q -> "subscription-userinfo: $q\r\n" }
                                            ?: "") +
                                        "Content-Type: text/plain; charset=utf-8\r\n" +
                                        "Content-Length: ${payload.size}\r\nConnection: close\r\n\r\n"
                            it.getOutputStream().write(response.toByteArray())
                            if (!redirect) it.getOutputStream().write(payload)
                            it.getOutputStream().flush()
                        }
                    }
                    responsesWritten.countDown()
                }
            }
        }
    }

    override fun close() {
        HttpsURLConnection.setDefaultSSLSocketFactory(previousFactory)
        responseGates.values.forEach { it.countDown() }
        socket.close()
        workers.shutdownNow()
    }
}

