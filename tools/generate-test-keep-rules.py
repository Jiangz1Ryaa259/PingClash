"""Trace release instrumentation references without shipping test code.

First run :app:writeReleaseTestTraceInputs with pingclashTestBuildType=release.
Uses the R8 bundled with the pinned AGP; no downloaded executable/dependency.
"""
from pathlib import Path
import os
import subprocess
import tomllib
import zipfile

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "app/build"
WORK = BUILD / "test-reference-inputs"


def class_entries(paths):
    for path in paths:
        if path.is_dir():
            for item in sorted(path.rglob("*.class")):
                yield item.relative_to(path).as_posix(), item.read_bytes()
        else:
            with zipfile.ZipFile(path) as archive:
                for name in sorted(archive.namelist()):
                    if name.endswith(".class") and not name.startswith("META-INF/"):
                        yield name, archive.read(name)


def jar(name, entries, excluded=()):
    names = set(excluded)
    with zipfile.ZipFile(WORK / name, "w", zipfile.ZIP_DEFLATED) as archive:
        for key, value in entries:
            if key in names:
                continue
            names.add(key)
            archive.writestr(zipfile.ZipInfo(key), value)
    return names


targets = [Path(p) for p in (WORK / "target.txt").read_text().splitlines()]
targets.append(BUILD / "intermediates/compile_app_classes_jar/release/bundleReleaseClassesToCompileJar/classes.jar")
target_names = jar("target.jar", class_entries(targets))
sources = [Path(p) for p in (WORK / "source.txt").read_text().splitlines()]
sources.extend([
    BUILD / "tmp/kotlin-classes/releaseAndroidTest",
    BUILD / "intermediates/javac/releaseAndroidTest/compileReleaseAndroidTestJavaWithJavac/classes",
])
jar("source.jar", class_entries(sources), target_names)
cache = Path(os.environ.get("GRADLE_USER_HOME", ROOT / ".tools/gradle"))
with (ROOT / "gradle/libs.versions.toml").open("rb") as catalog:
    agp = tomllib.load(catalog)["versions"]["agp"]
builders = list((cache / f"caches/modules-2/files-2.1/com.android.tools.build/builder/{agp}").glob("*/*.jar"))
if len(builders) != 1:
    raise SystemExit("Expected exactly one pinned AGP builder with R8")
java_home = Path(os.environ["JAVA_HOME"])
java = java_home / "bin" / ("java.exe" if os.name == "nt" else "java")
sdk = Path(os.environ.get("ANDROID_HOME", ROOT / ".tools/android-sdk"))
output = WORK / "traced.pro"
subprocess.run([
    str(java), "-Xmx1g", "-cp", str(builders[0]),
    "com.android.tools.r8.tracereferences.TraceReferences", "--keep-rules",
    "--lib", str(sdk / "platforms/android-35/android.jar"),
    "--source", str(WORK / "source.jar"), "--target", str(WORK / "target.jar"),
    "--map-diagnostics:MissingDefinitionsDiagnostic", "error", "warning",
    "--output", str(output),
], check=True)
rules = output.read_text()
if "kotlin.LazyKt" not in rules or "dev.pingclash.app" not in rules:
    raise SystemExit("Incomplete instrumentation reference graph")
header = ("# Generated by tools/generate-test-keep-rules.py using pinned R8.\n"
          "# Only symbols referenced from instrumentation; contains no test implementation.\n")
# TraceReferences sees calls from the external test APK, but not the inherited
# default-method contract on its anonymous InfiniteAnimationPolicy implementation.
# Preserve only this Compose test interface/default bridge, not the full library.
contracts = """
# Default-method contract implemented by the external Compose test APK.
-keep interface androidx.compose.ui.platform.InfiniteAnimationPolicy { *; }
-keep class androidx.compose.ui.platform.InfiniteAnimationPolicy$DefaultImpls { *; }
"""
(ROOT / "app/proguard-instrumentation.pro").write_text(header + rules + contracts, encoding="utf-8")
print(f"Traced instrumentation API: {rules.count('-keep ')} exact class rules")
